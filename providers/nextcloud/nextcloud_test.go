package nextcloud

import (
	"testing"

	"github.com/izetmolla/goauth"
)

func TestNew(t *testing.T) {
	t.Parallel()
	p, ok := New(Options{
		ClientID:     "client-id",
		ClientSecret: "client-secret",
		Issuer:       "https://issuer.example",
	}).(*goauth.OAuthProvider)
	if !ok {
		t.Fatalf("New() type = %T, want *goauth.OAuthProvider", New(Options{}))
	}
	if p.ID() != "nextcloud" {
		t.Fatalf("ID() = %q, want %q", p.ID(), "nextcloud")
	}
	if p.Name() != "Nextcloud" {
		t.Fatalf("Name() = %q, want %q", p.Name(), "Nextcloud")
	}
	if p.Type() != goauth.ProviderOAuth {
		t.Fatalf("Type() = %q, want %q", p.Type(), goauth.ProviderOAuth)
	}
	if p.ClientID != "client-id" || p.ClientSecret != "client-secret" {
		t.Fatalf("client credentials not wired: %q / %q", p.ClientID, p.ClientSecret)
	}
	if p.Profile == nil {
		t.Fatal("Profile is nil")
	}
	wantChecks := []goauth.Check{goauth.CheckState}
	if len(p.Checks) != len(wantChecks) {
		t.Fatalf("Checks = %#v, want %#v", p.Checks, wantChecks)
	}
	for i := range wantChecks {
		if p.Checks[i] != wantChecks[i] {
			t.Fatalf("Checks = %#v, want %#v", p.Checks, wantChecks)
		}
	}
	if p.Issuer == "" && p.AuthorizationURL == "" {
		t.Fatal("expected Issuer or AuthorizationURL")
	}
}

func TestNew_Overrides(t *testing.T) {
	t.Parallel()
	called := false
	custom := func(_ goauth.Profile, _ goauth.TokenSet) (*goauth.OAuthUser, error) {
		called = true
		return &goauth.OAuthUser{ID: "custom"}, nil
	}
	p := New(Options{
		ClientID:     "client-id",
		ClientSecret: "client-secret",
		Issuer:       "https://issuer.example",
		Scopes:       []string{"custom-scope"},
		Profile:      custom,
	}).(*goauth.OAuthProvider)
	if len(p.Scopes) != 1 || p.Scopes[0] != "custom-scope" {
		t.Fatalf("Scopes = %#v", p.Scopes)
	}
	u, err := p.Profile(goauth.Profile{}, goauth.TokenSet{})
	if err != nil || u.ID != "custom" || !called {
		t.Fatalf("custom profile not used: user=%#v err=%v called=%v", u, err, called)
	}
}

func TestDefaultProfile(t *testing.T) {
	t.Parallel()
	u, err := DefaultProfile(goauth.Profile{"ocs": map[string]any{"data": map[string]any{"id": "nc1", "displayname": "Next Cloud", "email": "n@c.com"}}}, goauth.TokenSet{})
	if err != nil {
		t.Fatal(err)
	}
	if u == nil {
		t.Fatal("nil user")
	}
	if u.ID != "nc1" {
		t.Fatalf("ID = %q, want %q", u.ID, "nc1")
	}
	if u.Email != "n@c.com" {
		t.Fatalf("Email = %q, want %q", u.Email, "n@c.com")
	}
	if u.Name != "Next Cloud" {
		t.Fatalf("Name = %q, want %q", u.Name, "Next Cloud")
	}
	if u.Provider != "nextcloud" {
		t.Fatalf("Provider = %q, want %q", u.Provider, "nextcloud")
	}
}
